-- User profiles, access grants, payment notifications, and auth bootstrap.
CREATE TABLE IF NOT EXISTS public.profiles (
  user_id uuid PRIMARY KEY,
  email varchar,
  created_at timestamptz
);
CREATE TABLE IF NOT EXISTS public.access_grants (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  is_unlocked boolean NOT NULL DEFAULT false,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.payment_click_notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  email text,
  amount numeric(10,2) NOT NULL DEFAULT 5.00,
  clicked_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.access_grants ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.payment_click_notifications ENABLE ROW LEVEL SECURITY;

GRANT SELECT ON public.profiles TO authenticated;
GRANT SELECT, INSERT, UPDATE ON public.access_grants TO authenticated;
GRANT INSERT ON public.payment_click_notifications TO anon, authenticated;
GRANT SELECT ON public.payment_click_notifications TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.payment_click_notifications_id_seq TO anon, authenticated;

DROP POLICY IF EXISTS users_view_own_profile ON public.profiles;
CREATE POLICY users_view_own_profile ON public.profiles
FOR SELECT TO authenticated USING (user_id = (SELECT auth.uid()));
DROP POLICY IF EXISTS admins_view_all_profiles ON public.profiles;
CREATE POLICY admins_view_all_profiles ON public.profiles
FOR SELECT TO authenticated
USING (EXISTS (SELECT 1 FROM public.admin_users a WHERE a.user_id = (SELECT auth.uid())));

DROP POLICY IF EXISTS users_view_own_access ON public.access_grants;
CREATE POLICY users_view_own_access ON public.access_grants
FOR SELECT TO authenticated USING (user_id = (SELECT auth.uid()));
DROP POLICY IF EXISTS "Only admin can view access" ON public.access_grants;
CREATE POLICY "Only admin can view access" ON public.access_grants
FOR SELECT TO authenticated
USING (EXISTS (SELECT 1 FROM public.admin_users a WHERE a.user_id = (SELECT auth.uid())));
DROP POLICY IF EXISTS "Only admin can insert access" ON public.access_grants;
CREATE POLICY "Only admin can insert access" ON public.access_grants
FOR INSERT TO authenticated
WITH CHECK (EXISTS (SELECT 1 FROM public.admin_users a WHERE a.user_id = (SELECT auth.uid())));
DROP POLICY IF EXISTS "Only admin can update access" ON public.access_grants;
CREATE POLICY "Only admin can update access" ON public.access_grants
FOR UPDATE TO authenticated
USING (EXISTS (SELECT 1 FROM public.admin_users a WHERE a.user_id = (SELECT auth.uid())))
WITH CHECK (EXISTS (SELECT 1 FROM public.admin_users a WHERE a.user_id = (SELECT auth.uid())));

DROP POLICY IF EXISTS "Anyone can register payment button clicks" ON public.payment_click_notifications;
CREATE POLICY "Anyone can register payment button clicks" ON public.payment_click_notifications
FOR INSERT TO anon, authenticated WITH CHECK (amount = 5.00);
DROP POLICY IF EXISTS "Admins can read payment click notifications" ON public.payment_click_notifications;
CREATE POLICY "Admins can read payment click notifications" ON public.payment_click_notifications
FOR SELECT TO authenticated
USING (EXISTS (SELECT 1 FROM public.admin_users a WHERE a.user_id = (SELECT auth.uid())));

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
BEGIN
  INSERT INTO public.profiles(user_id,email)
  VALUES (NEW.id,NEW.email)
  ON CONFLICT (user_id) DO NOTHING;
  INSERT INTO public.access_grants(user_id,is_unlocked)
  VALUES (NEW.id,false)
  ON CONFLICT (user_id) DO NOTHING;
  RETURN NEW;
END;
$function$;
REVOKE ALL ON FUNCTION public.handle_new_user() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();
