create table if not exists public.payment_click_notifications (
  id bigint generated by default as identity primary key,
  user_id uuid null references auth.users(id) on delete set null,
  email text null,
  amount numeric(10,2) not null default 5.00,
  clicked_at timestamptz not null default now()
);

alter table public.payment_click_notifications enable row level security;

drop policy if exists "Anyone can register payment button clicks" on public.payment_click_notifications;
create policy "Anyone can register payment button clicks"
on public.payment_click_notifications
for insert
to anon, authenticated
with check (amount = 5.00);

drop policy if exists "Admins can read payment click notifications" on public.payment_click_notifications;
create policy "Admins can read payment click notifications"
on public.payment_click_notifications
for select
to authenticated
using (
  exists (
    select 1
    from public.admin_users
    where admin_users.user_id = auth.uid()
  )
);

grant insert on public.payment_click_notifications to anon, authenticated;
grant select on public.payment_click_notifications to authenticated;
grant usage, select on sequence public.payment_click_notifications_id_seq to anon, authenticated;
